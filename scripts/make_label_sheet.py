"""Build the blind W3 label sheet and its KEY from reports/w3_label_sheet_source.json.

    python3 scripts/make_label_sheet.py            # write the sheet and the KEY
    python3 scripts/make_label_sheet.py --check    # fail if the committed files differ

Output is a pure function of the source file and SEED: rows are shuffled with
random.Random(SEED), then given row ids L01.., question ids Q01.. (in order of
first appearance) so neither order nor ids carry the question's split or group.
The sheet has only: row id, question id, question, chunk id, chunk text,
verdict, notes. Everything else goes to the KEY.
"""

from __future__ import annotations

import csv
import io
import json
import random
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "reports" / "w3_label_sheet_source.json"
SHEET = ROOT / "reports" / "W3-LABEL-SHEET.csv"
KEY = ROOT / "reports" / "W3-LABEL-SHEET-KEY.md"
SEED = 20261031
HEADER = ["row id", "question id", "question", "chunk id", "chunk text", "verdict", "notes"]
# Quote exceptions, explained in the KEY only (the quote is still verified).
EXCEPTIONS = {
    "p-013": "Artefact, not a judgment: this chunk holds the Matt 18:15 text, but the labelled quote begins with the word First, so it matches only wesley-049-c0013.",
    "p-030": "Same chunk as the p-009 row (wesley-024-c0012); the note and rank apply to both questions.",
}


def norm(s: str) -> str:
    return re.sub(r"\s+", " ", s)


def quote_segments(quote: str) -> list[str]:
    return [s for q in re.findall(r'"([^"]+)"', quote) for s in q.split(" ... ")]


def build() -> tuple[str, str, list[str]]:
    """Return (sheet csv text, key markdown, quote-verification failures)."""
    items = json.loads(SOURCE.read_text(encoding="utf-8"))
    order = list(range(len(items)))
    random.Random(SEED).shuffle(order)
    qmap: dict[str, str] = {}
    rows, keyrows, bad = [], [], []
    for pos, idx in enumerate(order, 1):
        it = items[idx]
        rid = f"L{pos:02d}"
        qid = qmap.setdefault(it["question_id"], f"Q{len(qmap) + 1:02d}")
        rows.append([rid, qid, it["question"], it["chunk_id"], it["chunk_text"], "", ""])
        for seg in quote_segments(it["quote"]):
            if norm(seg) not in norm(it["chunk_text"]):
                bad.append(f"{rid} {it['chunk_id']}: {seg[:60]}")
        keyrows.append((rid, qid, it))
    buf = io.StringIO(newline="")
    w = csv.writer(buf, lineterminator="\r\n")
    w.writerow(HEADER)
    w.writerows(rows)

    def cell(s: str) -> str:
        return s.replace("|", "\\|").replace("\n", "<br>")

    k = [
        "# W3-LABEL-SHEET-KEY",
        "",
        "**Director/analysis only: do not show to the labeller before verdicts are in.**",
        "",
        "Everything removed from `reports/W3-LABEL-SHEET.csv` so the sheet is blind. "
        "The sheet shows the labeller only: row id, opaque question id, question text, chunk id, chunk text, blank verdict, blank notes. "
        "It is generated by `scripts/make_label_sheet.py` from `reports/w3_label_sheet_source.json` "
        "(the 24 rows of the 3b9441b sheet, verbatim) and is byte-reproducible from the seed below.",
        "",
        f"- **Shuffle seed:** `{SEED}` (`random.Random(seed).shuffle` over the source rows in their original `#` order).",
        "- Row ids `L01`..`L24` follow the shuffled order. Question ids `Q01`.. are assigned in order of first appearance in that order.",
        "- Quote check: every quoted segment (split at ` ... `) appears in its own chunk text; the two explained exceptions are noted per row.",
        "- Diag note and rank are from section 4 of `reports/W3-RETRIEVAL-DIAG.md` (PR #42). A diag row groups chunks, so its rank applies to the whole diag row. "
        "\"Chunk rank\" is that chunk's own position in each ranker's top 5.",
        "",
        "| row id | sheet qid | real qid | group | orig # | chunk id | sermon | quote | chunk rank | diag note | diag rank | currently labelled passage(s) | exception |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for rid, qid, it in keyrows:
        k.append(
            "| " + " | ".join(cell(str(x)) for x in (
                rid, qid, it["question_id"], it["group"], it["orig_row"], it["chunk_id"], it["sermon"],
                it["quote"], it["sheet_rank"], it["diag_note"], it["diag_rank"], it["labelled"],
                EXCEPTIONS.get(it["question_id"], ""))) + " |"
        )
    return buf.getvalue(), "\n".join(k) + "\n", bad


def main(argv: list[str]) -> int:
    sheet, key, bad = build()
    if bad:
        print("quote not in chunk:", *bad, sep="\n  ")
        return 1
    if "--check" in argv:
        ok = SHEET.read_bytes() == sheet.encode() and KEY.read_bytes() == key.encode()
        print("up to date" if ok else "DIFFERS from committed files")
        return 0 if ok else 1
    SHEET.write_bytes(sheet.encode("utf-8"))
    KEY.write_bytes(key.encode("utf-8"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
